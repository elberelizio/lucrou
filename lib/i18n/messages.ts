function getLeaf(obj: Record<string, unknown> | string | undefined, path: string[]): string | undefined {
  if (!obj || typeof obj === 'string') return typeof obj === 'string' ? obj : undefined;
  const [head, ...rest] = path;
  if (!head) return undefined;
  const next = (obj as Record<string, unknown>)[head];
  if (rest.length === 0) return typeof next === 'string' ? next : undefined;
  if (next && typeof next === 'object' && !Array.isArray(next)) {
    return getLeaf(next as Record<string, unknown>, rest);
  }
  return undefined;
}

export function translate(
  locale: Locale,
  path: string,
  vars?: Record<string, string | number>
): string {
  const parts = path.split('.');
  let text = getLeaf(messages[locale], parts);
  if (text === undefined && locale !== 'en') {
    text = getLeaf(messages.en, parts);
  }
  if (text === undefined) text = path;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}
